const NEUTRAL = '#64748B';

/** The icon and its tile colours for a domain card, from what Databricks Discover sets. */
export function domainIconFor(dom: Pick<DomainHierarchy, 'domain'> & { icon: DomainIcon | null }): {
  Icon: LucideIcon;
  style: CSSProperties;
} {
  if (dom.domain === OTHER_DOMAIN) return { Icon: Shapes, style: { color: NEUTRAL, backgroundColor: `${NEUTRAL}1A` } };
  const color = /^#[0-9a-f]{6}$/i.test(dom.icon?.color ?? '') ? dom.icon!.color! : NEUTRAL;
  return {
    Icon: (dom.icon?.name && ICONS[dom.icon.name]) || Database,
    style: { color, backgroundColor: `${color}1A` },
  };
}
